    internal class SerialDecoder
    {
        private const int First_Byte = 0xFF; // 11111111
        private const int Second_Byte = 0x00; // 00000000
        private const int Data_Flag_Byte = 0xAA; // 10101010
        private const int Command_Flag_Byte = 0x55; // 01010101
        private const int Point_Wire_Size = 10; // 3B position + 3B force + 4B time, big-endian
        private const int Max_Command_Payload = 254; // 255 byte body minus the flag byte
        private enum Awaiting
        {
            First,
            Second,
            Third,
            DataLength,
            Data,
            CommandLength,
            CommandFlag,
            Command,
            Checksum,
        }
        private Awaiting messageState;

        private int messageSize;
        private List<int> dataBuffer;

        private List<DataPointRaw> points;
        private CommandPacket command; // command currently being parsed
        private Queue<CommandPacket> commands; // fully parsed commands, in arrival order

        public SerialDecoder()
        {
            messageState = Awaiting.First;
            messageSize = 0;
            dataBuffer = new List<int>();
            points = new List<DataPointRaw>();
            command = new CommandPacket(-1, "");
            commands = new Queue<CommandPacket>();
        }

        /// <summary>
        /// Builds a command frame: FF 00 55 [size] [flag] [payload...]
        /// where size = 1 + payload length (the flag counts), so a command
        /// with no arguments has size 1.
        /// </summary>
        public byte[] EncodeCommand(CommandPacket command)
        {
            byte[] payload = Encoding.Latin1.GetBytes(command.payload ?? "");
            if (payload.Length > Max_Command_Payload)
            {
                throw new ArgumentException("command payload longer than " + Max_Command_Payload + " bytes");
            }

            byte[] data = new byte[5 + payload.Length];
            data[0] = First_Byte;
            data[1] = Second_Byte;
            data[2] = Command_Flag_Byte;
            data[3] = (byte)(1 + payload.Length);
            data[4] = (byte)command.flag;
            payload.CopyTo(data, 5);
            return data;
        }

        public void Decode(List<int> data)
        {
            foreach (int b in data)
            {
                DecodeByte(b);
            }
        }

        public void Decode(byte[] data)
        {
            foreach (byte b in data)
            {
                DecodeByte((int)b);
            }
        }

        /// <summary>
        /// Flush and resets the accumulated buffer of points
        /// </summary>
        /// <param name="dataPoints"></param>
        /// <returns></returns>
        public bool TryGetPoints(out List<DataPointRaw> dataPoints)
        {
            if(points.Count > 0)
            {
                dataPoints = points;
                points = new List<DataPointRaw>();
                return true;
            }
            else
            {
                dataPoints = new List<DataPointRaw>();
                return false;
            }
        }
        public bool TryGetPoints(out List<DataPointRaw> dataPoints, int minimum)
        {
            if (points.Count >= minimum)
            {
                dataPoints = points;
                points = new List<DataPointRaw>();
                return true;
            }
            else
            {
                dataPoints = new List<DataPointRaw>();
                return false;
            }
        }
        public bool TryGetCommand(out CommandPacket outCommand)
        {
            // Pops the oldest pending command. Call in a loop until it returns
            // false, since one serial read can complete several commands.
            if (commands.Count > 0)
            {
                outCommand = commands.Dequeue();
                return true;
            }
            outCommand = new CommandPacket(-1, "");
            return false;
        }

        private void DecodeByte(int b)
        {
            // check current parser state
            switch (messageState)
            {
                case Awaiting.First:
                    if (b == First_Byte)
                    {
                        messageState = Awaiting.Second;
                    }
                    break;

                case Awaiting.Second:
                    if (b == Second_Byte) messageState = Awaiting.Third;
                    else messageState = Awaiting.First; // wrong byte, return to start
                    break;

                case Awaiting.Third:
                    if(b == Data_Flag_Byte)
                    {
                        messageState = Awaiting.DataLength;
                    }
                    else if (b == Command_Flag_Byte)
                    {
                        messageState = Awaiting.CommandLength;
                    }
                    else
                    {
                        messageState = Awaiting.First; // wrong byte, return to start
                    }
                    break;

                case Awaiting.DataLength:
                    messageSize = b;
                    dataBuffer = new List<int>();
                    messageState = Awaiting.Data;
                    break;

                case Awaiting.Data:
                    if (messageSize > 0)
                    {
                        dataBuffer.Add(b);
                        messageSize--;
                    }

                    if (messageSize == 0) // end of message
                    {
                        DecodeMessage();
                        messageState = Awaiting.First;
                    }
                    break;

                case Awaiting.CommandLength:
                    if (b == 0)
                    {
                        // a command always has at least its flag byte
                        messageState = Awaiting.First;
                        break;
                    }
                    messageSize = b - 1; // length includes the flag; this is the payload still to come

                    command = new CommandPacket(-1, "");

                    messageState = Awaiting.CommandFlag;
                    break;

                case Awaiting.CommandFlag:
                    command.flag = (CommandFlags)b;
                    if(messageSize > 0)
                    {
                        messageState = Awaiting.Command;
                    }
                    else
                    {
                        commands.Enqueue(command);
                        messageState = Awaiting.First;
                    }
                    break;

                case Awaiting.Command:
                    if (messageSize > 0)
                    {
                        command.payload += (char)b;
                        messageSize--;
                    }

                    if (messageSize == 0) // end of message
                    {
                        commands.Enqueue(command);
                        messageState = Awaiting.First;
                    }
                    break;

            } // end of switch()
        }

        private void DecodeMessage()
        {
            // Point layout (big-endian): position(3, signed) force(3, signed) time(4, unsigned).
            // A body that isn't a whole number of points is malformed: drop it.
            if (dataBuffer.Count % Point_Wire_Size != 0)
            {
                return;
            }

            for (int i = 0; i < dataBuffer.Count; i += Point_Wire_Size)
            {
                points.Add(new DataPointRaw
                {
                    position = MakeSigned24(dataBuffer.GetRange(i    , 3)),
                    force    = MakeSigned24(dataBuffer.GetRange(i + 3, 3)),
                    time     = MakeInt(dataBuffer.GetRange(i + 6, 4)),
                });
            }
        }

        /// <summary> 3 bytes, big-endian, two's complement -> signed int. </summary>
        private int MakeSigned24(List<int> b)
        {
            int u = (b[0] << 16) | (b[1] << 8) | b[2];
            return (u ^ 0x800000) - 0x800000; // sign-extend from bit 23
        }

        private int MakeInt(List<int> b)
        {
            int ret = 0;
            if(b.Count == 4)
            {
                ret += b[0] << 24;
                ret += b[1] << 16;
                ret += b[2] << 8;
                ret += b[3];
            }
            else if(b.Count == 3)
            {
                ret += b[0] << 16;
                ret += b[1] << 8;
                ret += b[2];
            }
            return ret;
        }

        public List<int> MockTransmission()
        {
            List<int> ret = new List<int>();
            ret.Add(0xFF);
            ret.Add(0);
            ret.Add(0xAA);
            ret.Add(160);
            for(int i = 0; i < 16; i++)
            {
                // position
                ret.Add(0);
                ret.Add(0);
                ret.Add(i<<2);
                // force
                ret.Add(i);
                ret.Add(i);
                ret.Add(i);
                // time
                ret.Add(0);
                ret.Add(0);
                ret.Add(0);
                ret.Add(i);
            }


            return ret;
        }
